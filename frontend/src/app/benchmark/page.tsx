"use client";

import React, { useEffect, useState } from "react";
import { FlaskConical, Info } from "lucide-react";
import { ApiError, BenchmarkResults, getBenchmark } from "@/lib/api";
import { Alert, Card, CardHeader, EmptyState, PageHeader, Skeleton } from "@/components/ui";
import { VerdictChip } from "@/components/Chips";
import { formatDateTime } from "@/lib/format";
import { cn } from "@/lib/utils";

function pct(n: number | undefined) {
  if (n === undefined || n === null || Number.isNaN(n)) return "-";
  return `${Number(n).toFixed(1)}%`;
}

function humanize(key: string) {
  return key.replace(/_/g, " ").replace(/^\w/, (c) => c.toUpperCase());
}

function Metric({ label, value, hint }: { label: string; value: string; hint?: string }) {
  return (
    <Card className="p-4 sm:p-5">
      <p className="text-xs font-medium text-muted">{label}</p>
      <p className="tabular mt-2 text-2xl font-semibold tracking-tight">{value}</p>
      {hint && <p className="mt-1 text-xs text-muted">{hint}</p>}
    </Card>
  );
}

export default function BenchmarkPage() {
  const [data, setData] = useState<BenchmarkResults | null>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    getBenchmark()
      .then(setData)
      .catch((err) => setError(err instanceof ApiError ? err.message : "Could not load benchmark results."));
  }, []);

  const header = (
    <PageHeader
      title="Benchmark"
      subtitle="How the Pramaan pipeline performs on a scripted set of mock UPI receipts: some clean, some tampered in known ways."
    />
  );

  const honesty = (
    <Alert tone="warning" icon={<Info className="h-5 w-5 text-suspicious" />} title="Results on our own synthetic test set of mock receipts. Not a measure of real-world accuracy.">
      The receipts are generated by our script in a generic UPI style with no real app branding, and the tamper operations are
      scripted. Real screenshots vary far more (themes, devices, camera photos), so treat these numbers as a regression check,
      not a guarantee. A screenshot alone cannot prove a payment; only the bank SMS match gives a confirmed result.
    </Alert>
  );

  if (error) {
    return (
      <div className="space-y-4">
        {header}
        <Alert tone="danger" title="Could not load benchmark results">
          {error}
        </Alert>
      </div>
    );
  }

  if (!data) {
    return (
      <div className="space-y-4">
        {header}
        <div className="grid grid-cols-2 gap-3 lg:grid-cols-5">
          {Array.from({ length: 5 }).map((_, i) => (
            <Skeleton key={i} className="h-24 rounded-2xl" />
          ))}
        </div>
        <Skeleton className="h-64 rounded-2xl" />
      </div>
    );
  }

  if (data.status === "pending" || !data.metrics || !data.confusion_matrix) {
    return (
      <div className="space-y-4">
        {header}
        {honesty}
        <Card>
          <EmptyState
            icon={<FlaskConical className="h-5 w-5" />}
            title="Benchmark has not been run yet"
            body="Generate the mock dataset and run the evaluation from the project root:"
            action={
              <pre className="rounded-xl bg-ink px-4 py-3 text-left text-xs text-white/90">
                python scripts/generate_dataset.py{"\n"}python scripts/evaluate_benchmark.py
              </pre>
            }
          />
        </Card>
      </div>
    );
  }

  const m = data.metrics;
  const cm = data.confusion_matrix;
  const perTamper = Object.entries(data.per_tamper ?? {});
  const samples = data.samples ?? [];

  return (
    <div className="space-y-6">
      {header}
      {honesty}

      <Card className="p-5">
        <div className="grid gap-4 text-sm sm:grid-cols-3">
          <div>
            <p className="text-xs text-muted">Dataset</p>
            <p className="font-medium">{data.dataset_name ?? "Synthetic mock receipts"}</p>
            {data.description && <p className="mt-1 text-xs text-muted">{data.description}</p>}
          </div>
          <div>
            <p className="text-xs text-muted">Samples</p>
            <p className="tabular font-medium">
              {data.total_samples ?? samples.length} total · {data.clean_samples ?? "-"} clean · {data.tampered_samples ?? "-"} tampered
            </p>
            {data.decision_rule && <p className="mt-1 text-xs text-muted">{data.decision_rule}</p>}
          </div>
          <div>
            <p className="text-xs text-muted">Evaluated</p>
            <p className="font-medium">{formatDateTime(data.evaluated_at)}</p>
            {data.generated_at && <p className="mt-1 text-xs text-muted">Dataset generated {formatDateTime(data.generated_at)}</p>}
          </div>
        </div>
      </Card>

      <div className="grid grid-cols-2 gap-3 lg:grid-cols-5">
        <Metric label="Precision" value={pct(m.precision)} hint="Flagged receipts that were really tampered" />
        <Metric label="Recall" value={pct(m.recall)} hint="Tampered receipts that were flagged" />
        <Metric label="F1 score" value={pct(m.f1_score)} />
        <Metric label="Accuracy" value={pct(m.accuracy)} />
        <Metric
          label="Avg. latency"
          value={`${Number(m.avg_latency_seconds).toFixed(2)}s`}
          hint={m.max_latency_seconds ? `Max ${Number(m.max_latency_seconds).toFixed(2)}s · target < 8s` : "Target < 8s"}
        />
      </div>

      <div className="grid items-start gap-6 lg:grid-cols-2">
        <Card>
          <CardHeader title="Confusion matrix" hint="Positive = tampered. A receipt counts as flagged if the verdict is Suspicious or Likely fake." />
          <div className="p-5">
            <div className="grid grid-cols-[auto_1fr_1fr] gap-2 text-sm">
              <div />
              <p className="pb-1 text-center text-xs font-medium text-muted">Predicted clean</p>
              <p className="pb-1 text-center text-xs font-medium text-muted">Predicted tampered</p>
              <p className="flex items-center pr-2 text-xs font-medium text-muted">Actually clean</p>
              <div className="rounded-xl bg-confirmed-soft p-4 text-center">
                <p className="tabular text-2xl font-semibold text-confirmed">{cm.true_negatives}</p>
                <p className="text-xs text-muted">True negative</p>
              </div>
              <div className={cn("rounded-xl p-4 text-center", cm.false_positives ? "bg-fake-soft" : "bg-paper")}>
                <p className={cn("tabular text-2xl font-semibold", cm.false_positives ? "text-fake" : "text-ink")}>{cm.false_positives}</p>
                <p className="text-xs text-muted">False positive</p>
              </div>
              <p className="flex items-center pr-2 text-xs font-medium text-muted">Actually tampered</p>
              <div className={cn("rounded-xl p-4 text-center", cm.false_negatives ? "bg-fake-soft" : "bg-paper")}>
                <p className={cn("tabular text-2xl font-semibold", cm.false_negatives ? "text-fake" : "text-ink")}>{cm.false_negatives}</p>
                <p className="text-xs text-muted">False negative</p>
              </div>
              <div className="rounded-xl bg-confirmed-soft p-4 text-center">
                <p className="tabular text-2xl font-semibold text-confirmed">{cm.true_positives}</p>
                <p className="text-xs text-muted">True positive</p>
              </div>
            </div>
          </div>
        </Card>

        <Card>
          <CardHeader title="Detection by tamper type" />
          {perTamper.length === 0 ? (
            <p className="px-5 py-6 text-sm text-muted">No per-type breakdown in this run.</p>
          ) : (
            <ul className="divide-y divide-line">
              {perTamper.map(([type, v]) => {
                const ratio = v.total ? v.detected / v.total : 0;
                return (
                  <li key={type} className="flex items-center gap-4 px-5 py-3">
                    <span className="min-w-0 flex-1 truncate text-sm">{humanize(type)}</span>
                    <div className="hidden h-1.5 w-24 overflow-hidden rounded-full bg-line sm:block">
                      <div className={cn("h-full", ratio === 1 ? "bg-confirmed" : ratio >= 0.5 ? "bg-suspicious" : "bg-fake")} style={{ width: `${ratio * 100}%` }} />
                    </div>
                    <span className="tabular w-12 text-right text-sm font-medium">
                      {v.detected}/{v.total}
                    </span>
                  </li>
                );
              })}
            </ul>
          )}
        </Card>
      </div>

      {samples.length > 0 && (
        <Card>
          <CardHeader title="Per-sample results" hint={`${samples.length} receipts`} />
          <div className="overflow-x-auto">
            <table className="w-full min-w-[720px] text-sm">
              <thead>
                <tr className="border-b border-line text-left text-xs text-muted">
                  <th className="px-4 py-3 font-medium">Sample</th>
                  <th className="px-4 py-3 font-medium">Label</th>
                  <th className="px-4 py-3 font-medium">Tamper type</th>
                  <th className="px-4 py-3 font-medium">Verdict</th>
                  <th className="px-4 py-3 text-right font-medium">Score</th>
                  <th className="px-4 py-3 font-medium">Top reason</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-line">
                {samples.map((s) => {
                  const flagged = s.predicted_tampered ?? (s.verdict === "SUSPICIOUS" || s.verdict === "LIKELY FAKE");
                  const correct = flagged === (s.label === "tampered");
                  return (
                    <tr key={s.id} className={cn(!correct && "bg-fake-soft/50")}>
                      <td className="px-4 py-2.5 font-mono text-xs">{s.id}</td>
                      <td className="px-4 py-2.5 capitalize">{s.label}</td>
                      <td className="px-4 py-2.5 text-muted">{s.tamper_type === "none" ? "-" : humanize(s.tamper_type)}</td>
                      <td className="px-4 py-2.5">
                        <VerdictChip verdict={s.verdict} />
                      </td>
                      <td className="tabular px-4 py-2.5 text-right">{Math.round(s.risk_score)}</td>
                      <td className="max-w-[260px] truncate px-4 py-2.5 text-muted" title={s.top_reason ?? s.reasons?.[0] ?? ""}>
                        {s.top_reason ?? s.reasons?.[0] ?? "-"}
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </Card>
      )}
    </div>
  );
}
